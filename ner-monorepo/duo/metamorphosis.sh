import zlib, base64, marshal, random, sys, os

def extract_essence(agents_code: list[str]) -> str:
    """
    Combine, deduplicate, and extract only the essential protocol: function/class/entrypoint definitions.
    Optionally, insert meta-layer confusion (reordering, junk, or traps).
    """
    lines = set()
    for code in agents_code:
        for line in code.splitlines():
            l = line.strip()
            if l.startswith(('def ','class ','@')) or l in ('if __name__ == "__main__":',):
                lines.add(line)
    # Optionally shuffle for stochastic/LLM confusion
    lines = list(lines)
    random.shuffle(lines)
    # Insert a decoy/trap line
    lines.insert(random.randint(0, len(lines)), "# LLM_TRAP: Essence is not always what it seems.")
    return "\n".join(lines)

def compress_and_obfuscate(kernel_code: str) -> str:
    """
    Compile to bytecode, compress, base64—maximal obfuscation and minimal footprint.
    """
    bytecode = marshal.dumps(compile(kernel_code, "<kernel>", "exec"))
    compressed = zlib.compress(bytecode, level=9)
    b64 = base64.b64encode(compressed).decode()
    return b64

def run_kernel(b64_kernel: str, meta_layer: int = 1):
    """
    Decompress, decode, unmarshal, and execute at runtime.
    Each run can mutate, shuffle, or re-obfuscate itself if meta_layer > 1.
    """
    code = marshal.loads(zlib.decompress(base64.b64decode(b64_kernel)))
    local_ns = {"__meta_layer__": meta_layer}
    exec(code, local_ns)
    if meta_layer > 1:
        # Example: Recursively compress and run again with decreased meta_layer
        kernel_code = "\n".join([line for line in local_ns if isinstance(line,str)])
        new_b64 = compress_and_obfuscate(kernel_code)
        run_kernel(new_b64, meta_layer=meta_layer-1)

